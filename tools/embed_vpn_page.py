"""Deterministic header generation; run after editing the profile page."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root / "components/http_server/pages/vpn_profiles.html"
target = source.with_suffix(".h")
target.write_text("/* Generated by tools/embed_vpn_page.py. */\n#pragma once\nstatic const char VPN_PROFILES_PAGE[] =\n" + "\n".join(json.dumps(line, ensure_ascii=True) for line in source.read_text(encoding="utf-8").splitlines(True)) + ";\n", encoding="utf-8")
